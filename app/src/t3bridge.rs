use crate::util::repo_root;
use serde_json::{json, Value};
use std::io::Write;
use std::process::{Command, Stdio};

pub fn call(cmd: &str, input: &Value) -> Result<Value, String> {
    let bridge = repo_root().join("third_party/t3code/bridge.mjs");
    if !bridge.exists() {
        return Err(format!("t3 bridge missing at {}", bridge.display()));
    }
    let mut child = Command::new("node")
        .arg("--experimental-strip-types")
        .arg(&bridge)
        .arg(cmd)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| format!("node bridge: {e}"))?;
    {
        let stdin = child.stdin.as_mut().ok_or("bridge stdin")?;
        stdin.write_all(input.to_string().as_bytes()).map_err(|e| e.to_string())?;
    }
    let out = child.wait_with_output().map_err(|e| e.to_string())?;
    if !out.status.success() {
        return Err(format!(
            "t3 bridge {cmd} failed: {}",
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    serde_json::from_slice(&out.stdout).map_err(|e| format!("bridge json: {e} {}", String::from_utf8_lossy(&out.stdout)))
}

pub fn thread_offsets(text: &str, query: &str) -> Result<Vec<usize>, String> {
    let v = call("thread-search", &json!({"text": text, "query": query}))?;
    Ok(v.get("offsets").and_then(|x| x.as_array()).map(|a| a.iter().filter_map(|n| n.as_u64().map(|u| u as usize)).collect()).unwrap_or_default())
}

pub fn rank(value: &str, query: &str) -> Result<Option<f64>, String> {
    let v = call("rank", &json!({"value": value.to_lowercase(), "query": query.to_lowercase()}))?;
    Ok(v.get("score").and_then(|s| s.as_f64()))
}

pub fn relative_path(path: &str, root: &str) -> Result<Option<String>, String> {
    let v = call("path-relative", &json!({"path": path, "root": root}))?;
    Ok(match &v["relative"] {
        Value::String(s) => Some(s.clone()),
        Value::Null => None,
        _ => None,
    })
}

pub fn host_class(host: &str) -> Result<Value, String> {
    call("host", &json!({"host": host}))
}

pub fn clean_commit_message(message: &str) -> Result<String, String> {
    let v = call("merge-message", &json!({"message": message}))?;
    Ok(v.get("message").and_then(|m| m.as_str()).unwrap_or(message).to_string())
}

pub fn model_short(name: &str, families: &[&str]) -> Result<Option<String>, String> {
    let v = call("model-short-name", &json!({"name": name, "families": families}))?;
    Ok(match &v["short"] {
        Value::String(s) => Some(s.clone()),
        _ => None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn vendored_modules_execute() {
        let offs = thread_offsets("Deploy the Deployment", "deploy").unwrap();
        assert_eq!(offs, vec![0, 11]);
        let short = model_short("Claude Opus 5.5", &["Claude "]).unwrap();
        assert_eq!(short.as_deref(), Some("Opus 5.5"));
        let rel = relative_path("/repo/../x", "/repo").unwrap();
        assert!(rel.is_none());
        let host = host_class("127.0.0.1").unwrap();
        assert_eq!(host["loopback"], true);
        assert_eq!(host["publicFavicon"], false);
        let cleaned = clean_commit_message("fix scan\n\nGenerated by Claude.\n").unwrap();
        assert!(!cleaned.to_lowercase().contains("generated by claude"));
        let score = rank("daily review", "review").unwrap();
        assert!(score.is_some());
    }
}
